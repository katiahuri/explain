// Builds the one-pager Katia takes into the room: the "Your instructor" slide, with the
// words to say underneath it. Page 1 is English, page 2 is the Hebrew delivery.
//
// The slide itself is the same object the decks render, read from module-00.json, so it
// cannot drift from the deck. The page look is the printable deck's, reused wholesale.
//
// Output: course/slides/ExplAIn-About-Katia.html, which package.py prints to PDF.
const fs = require('fs');
const path = require('path');
const { printBody, CSS, FIT } = require('./print-deck');

const ROOT = path.resolve(__dirname, '..', '..');

function buildAboutSlide() {
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const m = JSON.parse(fs.readFileSync(path.join(ROOT, 'course', 'content', 'module-00.json'), 'utf8'));
const slide = m.slides.find((s) => s.type === 'bio');
if (!slide) throw new Error('no bio slide in module-00.json');

const EN = [
  'Good morning. I am Katia. Before I tell you what we are doing in this hour, two minutes on why I am the one standing here.',
  'I have been doing this for almost twenty years. Computer science, B.Sc. and M.Sc., and from there the whole stack: frontend, backend, data engineering, data science, and all the way down to inference optimization, which means making a model run fast and cheap on real hardware. Deep learning and computer vision. Three patents. A startup that was acquired for its team. I have led teams of engineers, analysts and data scientists. I trained and taught neural networks before it was cool.',
  'I am not telling you this for the CV. I am telling you so you know where today’s examples come from, and so you know you can ask me the questions that are not on the slide.',
  'And why I built this course. I kept seeing the same thing: strong engineers, using AI every day, shipping with it, and still guessing. Not because they could not understand it. Because nobody ever showed them the layer beneath the interface.',
  'So that is what you get here. Not prompts. Prompts expire, and the trick that worked in January is useless by June. The system underneath does not expire.',
];

const HE = [
  'בוקר טוב. אני קטיה. לפני שאני אומרת מה נעשה בשעה הזאת, שתי דקות על למה אני זאת שעומדת פה.',
  'אני בתחום חמש עשרה שנים. מדעי המחשב, תואר ראשון ושני, ומשם כל הסטאק: פרונטאנד, בקאנד, דאטה אנג׳ינירינג, דאטה סיינס, וגם למטה, עד אופטימיזציה של אינפרנס. זה אומר לגרום למודל לרוץ מהר וזול על חומרה אמיתית. דיפ לרנינג וראייה ממוחשבת. שלושה פטנטים. סטארטאפ שנקנה בשביל הצוות שלו. הובלתי צוותים של מהנדסים, אנליסטים ואנשי דאטה סיינס. אימנתי ולימדתי רשתות נוירונים עוד לפני שזה היה טרנדי.',
  'אני לא מספרת את זה בשביל קורות החיים. אני מספרת את זה כדי שתדעו מאיפה באות הדוגמאות שתשמעו היום, ושתדעו שאפשר לשאול אותי גם שאלות שהתשובה להן היא לא על השקף.',
  'ולמה בניתי את הקורס הזה. כי ראיתי את אותו דבר קורה שוב ושוב: אנשים חזקים, שמשתמשים ב-AI כל יום וגם מעלים איתו דברים לאוויר, ובכל זאת מנחשים. לא כי הם לא מסוגלים להבין. כי אף אחד לא הראה להם את השכבה שמתחת לממשק.',
  'אז זה מה שאני עושה פה. אני לא מלמדת פרומפטים. פרומפטים מתיישנים, הטריק שעבד בינואר לא רלוונטי ביוני. אני מלמדת את המערכת שמתחת, והיא לא מתיישנת.',
];

const deco = '<div class="deco" aria-hidden="true"><i></i><b></b><s></s></div>';
const body = printBody(slide, m, { esc, mapBoxes: [] });

const page = (label, note, lines, dir) => `
  <section class="page">
    <div class="runner"><b>EXPLAIN · YOUR INSTRUCTOR</b><span>${esc(label)}</span></div>
    <div class="frame">
      <div class="inner t-${slide.type}">
        ${deco}
        <div class="well"><div class="stage">
          ${slide.eyebrow ? `<p class="eyebrow">${esc(slide.eyebrow)}</p>` : ''}
          ${body}
        </div></div>
      </div>
      <div class="notes"${dir === 'rtl' ? ' dir="rtl"' : ''}>
        <h3>${esc(note)}</h3>
        <div class="body">${lines.map((p) => `<p>${esc(p)}</p>`).join('')}</div>
      </div>
    </div>
  </section>`;

const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>ExplAIn — Your instructor — the slide and what to say</title>
  <meta name="robots" content="noindex">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Space+Grotesk:wght@500;700&family=Inter:wght@400;600;700&display=swap" rel="stylesheet">
  <!-- Generated by course/_build/about-slide.js from course/content/module-00.json — edit the JSON and the script, not this file. -->
  <style>${CSS}
    .notes[dir="rtl"] .body { font-size: 10.5pt; line-height: 1.7; }
  </style>
</head>
<body>
${page('English · 1 / 2', 'What to say', EN, 'ltr')}
${page('Hebrew · 2 / 2', 'מה להגיד', HE, 'rtl')}
  <script>${FIT}
  </script>
</body>
</html>
`;

const out = path.join(ROOT, 'course', 'slides', 'ExplAIn-About-Katia.html');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, html);
return path.relative(ROOT, out);
}

module.exports = { buildAboutSlide };

if (require.main === module) console.log(`✓ ${buildAboutSlide()}`);
