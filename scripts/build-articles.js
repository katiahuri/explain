const block = (b) => {
  if (b.type === 'p') return `<p>${esc(b.text)}</p>`;
  if (b.type === 'h2') return `<h2>${esc(b.text)}</h2>`;
  if (b.type === 'ul') return `<ul>${b.items.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>`;
  if (b.type === 'ol') return `<ol>${b.items.map((i) => `<li>${esc(i)}</li>`).join('')}</ol>`;
  if (b.type === 'quote') return `<blockquote>${esc(b.text)}</blockquote>`;
  if (b.type === 'figure') return FIGURES[b.figure] || '';
  if (b.type === 'table') {
    return `<table><tr>${b.columns.map((c) => `<th scope="col">${esc(c)}</th>`).join('')}</tr>` +
      b.rows.map((r) => `<tr>${r.map((c) => `<td>${esc(c)}</td>`).join('')}</tr>`).join('') + '</table>';
  }
  return '';
};

