//   newsletter.html              the archive, one card per issue
//   newsletter-<slug>.html       one page per issue, written to be found
//   email-drafts/<slug>.html     the same issue as a single-column email
//
// The archive and issue pages ship with the site; the email draft is for
// pasting into whatever sends the mail, and is never deployed.
// Usage: node scripts/build-newsletter.js
