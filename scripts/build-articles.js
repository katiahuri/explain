const emailBlock = (b) => {
  const p = 'margin:0 0 18px; font:16px/1.7 Helvetica,Arial,sans-serif; color:#3f4859;';
  if (b.type === 'p') return `<p style="${p}">${esc(b.text)}</p>`;
  if (b.type === 'h2') return `<h2 style="margin:34px 0 14px; font:600 22px/1.3 Helvetica,Arial,sans-serif; color:#0b1026;">${esc(b.text)}</h2>`;
  if (b.type === 'ul' || b.type === 'ol') {
    const tag = b.type === 'ul' ? 'ul' : 'ol';
    return `<${tag} style="${p} padding-left:22px;">${b.items.map((i) => `<li style="margin:0 0 10px;">${esc(i)}</li>`).join('')}</${tag}>`;
  }
  if (b.type === 'quote') {
    return `<p style="margin:26px 0; padding:16px 20px; border-left:3px solid #7c3aed; background:#f6f4ff; font:600 18px/1.5 Helvetica,Arial,sans-serif; color:#0b1026;">${esc(b.text)}</p>`;
  }
  if (b.type === 'table') {
    const th = 'padding:10px 12px; border-bottom:2px solid #e4e8f1; text-align:left; font:600 13px/1.4 Helvetica,Arial,sans-serif; color:#0b1026;';
    const td = 'padding:10px 12px; border-bottom:1px solid #e4e8f1; font:14px/1.6 Helvetica,Arial,sans-serif; color:#3f4859; vertical-align:top;';
    return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:0 0 22px; border-collapse:collapse;"><tr>${
      b.columns.map((c) => `<th style="${th}">${esc(c)}</th>`).join('')}</tr>${
      b.rows.map((r) => `<tr>${r.map((c) => `<td style="${td}">${esc(c)}</td>`).join('')}</tr>`).join('')}</table>`;
  }
  return '';
};

